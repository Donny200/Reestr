-- Anonymous visitor questions ("Ask a question"), separate from information reports. A visitor follows a conversation
-- only through a random access token that is shown to them once; the database keeps its SHA-256 hash, never the token.
-- organization_id is NULL for general questions, which only global staff (SUPER_ADMIN) see. notify_email is optional,
-- used only for reply notifications and cleared when the conversation is closed.
CREATE TABLE IF NOT EXISTS help_conversations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    access_token_hash VARCHAR(64) NOT NULL,
    function_id BIGINT,
    organization_id BIGINT,
    subject_label VARCHAR(150),
    language VARCHAR(35),
    status VARCHAR(20) NOT NULL,
    assigned_user_id BIGINT,
    assigned_user_name VARCHAR(320),
    notify_email VARCHAR(254),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    last_visitor_message_at TIMESTAMP WITH TIME ZONE NOT NULL,
    last_staff_reply_at TIMESTAMP WITH TIME ZONE,
    closed_at TIMESTAMP WITH TIME ZONE,
    version BIGINT,
    CONSTRAINT help_conversations_token_key UNIQUE (access_token_hash),
    CONSTRAINT help_conversations_status_check CHECK (status IN ('NEW', 'IN_PROGRESS', 'ANSWERED', 'CLOSED'))
);
CREATE INDEX IF NOT EXISTS help_conversations_inbox_idx ON help_conversations(organization_id, status, updated_at DESC);
CREATE INDEX IF NOT EXISTS help_conversations_assignee_idx ON help_conversations(assigned_user_id);

CREATE TABLE IF NOT EXISTS help_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT NOT NULL REFERENCES help_conversations(id),
    author VARCHAR(10) NOT NULL,
    staff_user_id BIGINT,
    staff_label VARCHAR(320),
    body VARCHAR(2000) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT help_messages_author_check CHECK (author IN ('VISITOR', 'STAFF'))
);
CREATE INDEX IF NOT EXISTS help_messages_conversation_idx ON help_messages(conversation_id, created_at, id);

-- Persistent support chat on top of the visitor questions of V11 (additive; nothing is dropped).
--
-- Every visitor has one support identity ("guest"): either a signed-in account (user_id) or an anonymous browser.
-- An anonymous browser is recognised by a random secret in an HttpOnly, SameSite=Strict cookie; only its SHA-256 hash
-- is stored in help_guest_sessions. An optional recovery code (hash only) lets the visitor attach another browser.
-- The optional contact e-mail lives on the guest and is used only for support follow-up.
CREATE TABLE IF NOT EXISTS help_guests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT,
    recovery_code_hash VARCHAR(64),
    contact_email VARCHAR(254),
    notify_by_email BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    last_seen_at TIMESTAMP WITH TIME ZONE NOT NULL,
    version BIGINT,
    CONSTRAINT help_guests_user_key UNIQUE (user_id),
    CONSTRAINT help_guests_recovery_key UNIQUE (recovery_code_hash)
);
CREATE INDEX IF NOT EXISTS help_guests_seen_idx ON help_guests(last_seen_at);

CREATE TABLE IF NOT EXISTS help_guest_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    guest_id BIGINT NOT NULL REFERENCES help_guests(id) ON DELETE CASCADE,
    secret_hash VARCHAR(64) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    last_seen_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT help_guest_sessions_secret_key UNIQUE (secret_hash)
);
CREATE INDEX IF NOT EXISTS help_guest_sessions_guest_idx ON help_guest_sessions(guest_id);
CREATE INDEX IF NOT EXISTS help_guest_sessions_seen_idx ON help_guest_sessions(last_seen_at);

-- A guest has one support thread. Behind it there is one conversation per responsible organization (and one for
-- central support), so organization staff only ever see the part of the thread that belongs to them.
-- The per-conversation access token of V11 is no longer issued; existing rows keep their value.
ALTER TABLE help_conversations ALTER COLUMN access_token_hash DROP NOT NULL;
ALTER TABLE help_conversations ADD COLUMN IF NOT EXISTS guest_id BIGINT REFERENCES help_guests(id) ON DELETE SET NULL;
ALTER TABLE help_conversations ADD COLUMN IF NOT EXISTS last_message_at TIMESTAMP WITH TIME ZONE;
UPDATE help_conversations SET last_message_at = GREATEST(last_visitor_message_at, COALESCE(last_staff_reply_at, last_visitor_message_at))
WHERE last_message_at IS NULL;
CREATE UNIQUE INDEX IF NOT EXISTS help_conversations_guest_route_key
    ON help_conversations(guest_id, COALESCE(organization_id, -1)) WHERE guest_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS help_conversations_last_message_idx ON help_conversations(last_message_at DESC);

-- Messages carry the service (or organization) they are about, an optional category for reports of incorrect
-- information (with the id of the report created for the editorial workflow), the sender's idempotency key and the
-- moment the recipient side read them.
ALTER TABLE help_messages ADD COLUMN IF NOT EXISTS client_message_id VARCHAR(64);
ALTER TABLE help_messages ADD COLUMN IF NOT EXISTS read_at TIMESTAMP WITH TIME ZONE;
ALTER TABLE help_messages ADD COLUMN IF NOT EXISTS function_id BIGINT;
ALTER TABLE help_messages ADD COLUMN IF NOT EXISTS context_label VARCHAR(150);
ALTER TABLE help_messages ADD COLUMN IF NOT EXISTS category VARCHAR(40);
ALTER TABLE help_messages ADD COLUMN IF NOT EXISTS report_id BIGINT;
CREATE UNIQUE INDEX IF NOT EXISTS help_messages_client_id_key
    ON help_messages(conversation_id, author, client_message_id) WHERE client_message_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS help_messages_unread_idx ON help_messages(conversation_id, author) WHERE read_at IS NULL;

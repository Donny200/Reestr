-- Appointment booking with organization-managed availability (additive; no existing table is changed).
--
-- There is no external government scheduling integration: each organization publishes its own availability on this
-- site (weekly hours with an optional break, slot length, parallel desks, booking window, closures), and a booking
-- reserves one desk ("seat") of one slot in that calendar. Double booking is prevented by the database: a seat of a
-- slot can be held by at most one BOOKED appointment (partial unique index below), and bookings of one organization
-- are serialized by locking its schedule row.
CREATE TABLE IF NOT EXISTS appointment_schedules (
    organization_id BIGINT PRIMARY KEY,
    enabled BOOLEAN NOT NULL DEFAULT FALSE,
    time_zone VARCHAR(64) NOT NULL DEFAULT 'Asia/Tashkent',
    slot_minutes INTEGER NOT NULL DEFAULT 30,
    capacity INTEGER NOT NULL DEFAULT 1,
    booking_horizon_days INTEGER NOT NULL DEFAULT 30,
    min_notice_minutes INTEGER NOT NULL DEFAULT 120,
    visitor_note VARCHAR(500),
    weekly_hours JSONB,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_by_user_id BIGINT,
    version BIGINT,
    CONSTRAINT appointment_schedules_slot_check CHECK (slot_minutes BETWEEN 5 AND 240),
    CONSTRAINT appointment_schedules_capacity_check CHECK (capacity BETWEEN 1 AND 50),
    CONSTRAINT appointment_schedules_horizon_check CHECK (booking_horizon_days BETWEEN 1 AND 365),
    CONSTRAINT appointment_schedules_notice_check CHECK (min_notice_minutes BETWEEN 0 AND 20160)
);

-- Holidays, closed dates and unavailable periods (local dates/times of the schedule's time zone). Without times the
-- whole day is closed; with times only that part of each day in the range.
CREATE TABLE IF NOT EXISTS appointment_closures (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL,
    kind VARCHAR(20) NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    start_time TIME,
    end_time TIME,
    note VARCHAR(200),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    created_by_user_id BIGINT,
    CONSTRAINT appointment_closures_kind_check CHECK (kind IN ('HOLIDAY', 'CLOSED', 'UNAVAILABLE')),
    CONSTRAINT appointment_closures_dates_check CHECK (end_date >= start_date),
    CONSTRAINT appointment_closures_times_check CHECK ((start_time IS NULL AND end_time IS NULL)
        OR (start_time IS NOT NULL AND end_time IS NOT NULL AND end_time > start_time))
);
CREATE INDEX IF NOT EXISTS appointment_closures_org_idx ON appointment_closures(organization_id, end_date);

-- One appointment of a visitor. Visitors manage it with the booking reference and a secret access token chosen by
-- their browser; only the token's SHA-256 hash is stored. Contact details are the minimum needed to manage the
-- appointment and are removed some time after the appointment (catalog.appointments.contact-retention).
CREATE TABLE IF NOT EXISTS appointments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference VARCHAR(12) NOT NULL,
    organization_id BIGINT NOT NULL,
    function_id BIGINT NOT NULL,
    function_name VARCHAR(150) NOT NULL,
    starts_at TIMESTAMP WITH TIME ZONE NOT NULL,
    ends_at TIMESTAMP WITH TIME ZONE NOT NULL,
    seat INTEGER NOT NULL DEFAULT 1,
    time_zone VARCHAR(64) NOT NULL,
    status VARCHAR(20) NOT NULL,
    cancelled_by VARCHAR(10),
    visitor_name VARCHAR(100),
    visitor_phone VARCHAR(30),
    visitor_email VARCHAR(254),
    language VARCHAR(35),
    access_token_hash VARCHAR(64) NOT NULL,
    client_request_id VARCHAR(64) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    cancelled_at TIMESTAMP WITH TIME ZONE,
    contact_removed_at TIMESTAMP WITH TIME ZONE,
    handled_by_user_id BIGINT,
    version BIGINT,
    CONSTRAINT appointments_reference_key UNIQUE (reference),
    CONSTRAINT appointments_client_request_key UNIQUE (client_request_id),
    CONSTRAINT appointments_status_check CHECK (status IN ('BOOKED', 'CANCELLED', 'ATTENDED', 'NO_SHOW')),
    CONSTRAINT appointments_cancelled_by_check CHECK (cancelled_by IS NULL OR cancelled_by IN ('VISITOR', 'STAFF')),
    CONSTRAINT appointments_times_check CHECK (ends_at > starts_at),
    CONSTRAINT appointments_seat_check CHECK (seat >= 1)
);
CREATE UNIQUE INDEX IF NOT EXISTS appointments_booked_seat_key
    ON appointments(organization_id, starts_at, seat) WHERE status = 'BOOKED';
CREATE INDEX IF NOT EXISTS appointments_org_start_idx ON appointments(organization_id, starts_at);
CREATE INDEX IF NOT EXISTS appointments_retention_idx ON appointments(starts_at) WHERE contact_removed_at IS NULL;

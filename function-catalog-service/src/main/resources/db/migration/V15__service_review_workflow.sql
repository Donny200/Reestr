-- Multi-step service editor and field-level review. Additive: existing cards keep their status, content and history.

-- 1. "Changes requested": an editable state a reviewer returns a submission to with notes on specific fields.
--    Unlike a rejection it keeps the review cycle open; the author corrects the flagged fields and resubmits.
ALTER TABLE org_functions DROP CONSTRAINT IF EXISTS org_functions_status_check;
ALTER TABLE org_functions ADD CONSTRAINT org_functions_status_check
    CHECK (status IN ('DRAFT', 'PENDING_REVIEW', 'CHANGES_REQUESTED', 'PUBLISHED', 'DEACTIVATED'));
ALTER TABLE org_functions DROP CONSTRAINT IF EXISTS org_functions_revision_status_check;
ALTER TABLE org_functions ADD CONSTRAINT org_functions_revision_status_check
    CHECK (revision_of_id IS NULL OR status IN ('DRAFT', 'PENDING_REVIEW', 'CHANGES_REQUESTED'));

-- 2. Staff-only service profile shown in the "Digitalization" and "Decentralization and risk assessment" steps.
--    All nullable: existing cards simply have no profile yet. Never part of public responses.
ALTER TABLE org_functions ADD COLUMN IF NOT EXISTS delivery_channel VARCHAR(30);
ALTER TABLE org_functions ADD COLUMN IF NOT EXISTS online_service_url VARCHAR(500);
ALTER TABLE org_functions ADD COLUMN IF NOT EXISTS provision_level VARCHAR(30);
ALTER TABLE org_functions ADD COLUMN IF NOT EXISTS risk_level VARCHAR(20);
ALTER TABLE org_functions ADD COLUMN IF NOT EXISTS risk_notes VARCHAR(2000);
ALTER TABLE org_functions ADD CONSTRAINT org_functions_delivery_channel_check
    CHECK (delivery_channel IS NULL OR delivery_channel IN ('IN_PERSON', 'ONLINE', 'ONLINE_AND_IN_PERSON'));
ALTER TABLE org_functions ADD CONSTRAINT org_functions_provision_level_check
    CHECK (provision_level IS NULL OR provision_level IN ('NATIONAL', 'REGIONAL', 'DISTRICT'));
ALTER TABLE org_functions ADD CONSTRAINT org_functions_risk_level_check
    CHECK (risk_level IS NULL OR risk_level IN ('LOW', 'MEDIUM', 'HIGH'));

-- 3. Editor state: the step the author last saved from (so a draft resumes there) and the review cycle counter
--    (incremented on every submission; review notes and section marks carry the cycle they belong to).
ALTER TABLE org_functions ADD COLUMN IF NOT EXISTS editor_step VARCHAR(30);
ALTER TABLE org_functions ADD COLUMN IF NOT EXISTS review_cycle INTEGER NOT NULL DEFAULT 0;
-- Cards already under review are in their first cycle.
UPDATE org_functions SET review_cycle = 1 WHERE status = 'PENDING_REVIEW' AND review_cycle = 0;

-- 4. Stable ids for structured document details, so review notes stay attached to the right item when the list
--    is reordered. Existing details get a random id; the public content fingerprint ignores ids.
UPDATE org_functions
SET document_details = (
    SELECT jsonb_agg(CASE WHEN detail ? 'id' THEN detail ELSE detail || jsonb_build_object('id', gen_random_uuid()::text) END
                     ORDER BY position)
    FROM jsonb_array_elements(document_details) WITH ORDINALITY AS item(detail, position)
)
WHERE document_details IS NOT NULL AND jsonb_typeof(document_details) = 'array' AND jsonb_array_length(document_details) > 0;

-- 5. Field-level review notes. One row per note; never deleted. A note is OPEN until the author changes the field and
--    resubmits (ADDRESSED), a reviewer resolves it (REVIEWER_RESOLVED) or its draft revision is discarded.
--    value_hash is the SHA-256 of the field value the reviewer saw, so "changed since review" is decided on the server.
CREATE TABLE IF NOT EXISTS function_review_comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    function_id BIGINT NOT NULL REFERENCES org_functions(id),
    field_path VARCHAR(200) NOT NULL,
    section VARCHAR(30) NOT NULL,
    review_cycle INTEGER NOT NULL,
    comment VARCHAR(2000) NOT NULL,
    value_hash VARCHAR(64) NOT NULL,
    status VARCHAR(20) NOT NULL,
    reviewer_user_id BIGINT,
    reviewer VARCHAR(320) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    resolution VARCHAR(30),
    resolved_by_user_id BIGINT,
    resolved_by VARCHAR(320),
    resolved_at TIMESTAMP WITH TIME ZONE,
    resolved_in_cycle INTEGER,
    CONSTRAINT function_review_comments_status_check CHECK (status IN ('OPEN', 'RESOLVED')),
    CONSTRAINT function_review_comments_resolution_check
        CHECK (resolution IS NULL OR resolution IN ('ADDRESSED', 'REVIEWER_RESOLVED', 'REVISION_DISCARDED')),
    CONSTRAINT function_review_comments_resolved_check CHECK ((status = 'OPEN') = (resolution IS NULL)),
    CONSTRAINT function_review_comments_text_check CHECK (length(btrim(comment)) > 0)
);
CREATE INDEX IF NOT EXISTS function_review_comments_function_idx ON function_review_comments(function_id, created_at);
-- At most one open note per field: a second flag on the same field is a duplicate review action.
CREATE UNIQUE INDEX IF NOT EXISTS function_review_comments_open_idx
    ON function_review_comments(function_id, field_path) WHERE status = 'OPEN';

-- 6. "Section reviewed" marks of the reviewer checklist, per review cycle.
CREATE TABLE IF NOT EXISTS function_review_marks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    function_id BIGINT NOT NULL REFERENCES org_functions(id),
    review_cycle INTEGER NOT NULL,
    section VARCHAR(30) NOT NULL,
    reviewer_user_id BIGINT,
    reviewer VARCHAR(320) NOT NULL,
    reviewed_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT function_review_marks_key UNIQUE (function_id, review_cycle, section)
);

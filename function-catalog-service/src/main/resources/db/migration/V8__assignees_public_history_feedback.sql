-- Public change history: one row per approved publication of a card. Only the publication moment, the kind of
-- publication and the names of the public sections that changed are stored; no draft text, notes or user ids.
CREATE TABLE IF NOT EXISTS function_public_changes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    function_id BIGINT NOT NULL REFERENCES org_functions(id),
    published_at TIMESTAMP WITH TIME ZONE NOT NULL,
    change_type VARCHAR(30) NOT NULL,
    sections JSONB NOT NULL,
    section_hashes JSONB,
    CONSTRAINT function_public_changes_type_check CHECK (change_type IN ('FIRST_PUBLICATION', 'UPDATE', 'REPUBLISHED'))
);
CREATE INDEX IF NOT EXISTS function_public_changes_function_idx ON function_public_changes(function_id, published_at DESC);

-- Anonymous "Was this information helpful?" votes, aggregated per day and card like engagement counts.
CREATE TABLE IF NOT EXISTS feedback_daily_counts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activity_date DATE NOT NULL,
    function_id BIGINT NOT NULL REFERENCES org_functions(id),
    organization_id BIGINT,
    helpful_count BIGINT NOT NULL DEFAULT 0,
    not_helpful_count BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT feedback_daily_counts_key UNIQUE (activity_date, function_id),
    CONSTRAINT feedback_daily_counts_nonnegative CHECK (helpful_count >= 0 AND not_helpful_count >= 0)
);
CREATE INDEX IF NOT EXISTS feedback_daily_counts_scope_idx ON feedback_daily_counts(organization_id, activity_date);

-- Background machine-translation queue. One row per card or category; the worker fills only the translations that are
-- still missing for the languages active in identity-service, so re-running a job never calls the provider twice for
-- the same text. No translated content is stored here: only the scheduling state and a short, secret-free error note.
CREATE TABLE IF NOT EXISTS translation_jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    target_type VARCHAR(20) NOT NULL,
    target_id BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL,
    attempts INTEGER NOT NULL DEFAULT 0,
    requested_at TIMESTAMP WITH TIME ZONE NOT NULL,
    next_attempt_at TIMESTAMP WITH TIME ZONE NOT NULL,
    finished_at TIMESTAMP WITH TIME ZONE,
    last_error VARCHAR(500),
    CONSTRAINT translation_jobs_target_unique UNIQUE (target_type, target_id),
    CONSTRAINT translation_jobs_type_check CHECK (target_type IN ('FUNCTION', 'CATEGORY')),
    CONSTRAINT translation_jobs_status_check CHECK (status IN ('PENDING', 'RUNNING', 'DONE', 'FAILED', 'SKIPPED'))
);
CREATE INDEX IF NOT EXISTS translation_jobs_due_idx ON translation_jobs(status, next_attempt_at);

-- Language of the category name as entered by staff; lets the queue translate category names like card content.
ALTER TABLE function_categories ADD COLUMN IF NOT EXISTS source_language VARCHAR(35);

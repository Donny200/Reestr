-- Single-use, hashed password reset tokens and the credentials timestamp that invalidates older access tokens.
-- Guarded like V2/V3: on a fresh database Hibernate creates the schema from the entities.
DO $migration$
BEGIN
    IF to_regclass('public.users') IS NOT NULL THEN
        ALTER TABLE users
            ADD COLUMN IF NOT EXISTS credentials_updated_at TIMESTAMP WITH TIME ZONE;
        CREATE TABLE IF NOT EXISTS password_reset_tokens (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            token_hash VARCHAR(64) NOT NULL UNIQUE,
            user_id BIGINT NOT NULL REFERENCES users(id),
            channel VARCHAR(20) NOT NULL,
            initiated_by_user_id BIGINT,
            created_at TIMESTAMP WITH TIME ZONE NOT NULL,
            expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
            used_at TIMESTAMP WITH TIME ZONE,
            invalidated_at TIMESTAMP WITH TIME ZONE
        );
        CREATE INDEX IF NOT EXISTS password_reset_tokens_user_idx ON password_reset_tokens(user_id);
    END IF;
END;
$migration$;

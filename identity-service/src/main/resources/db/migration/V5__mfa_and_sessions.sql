-- Second factor for staff accounts and session management. Guarded like V2-V4: on a fresh database Hibernate
-- creates the schema from the entities. Secrets are stored encrypted (AES-GCM, key from MFA_ENCRYPTION_KEY),
-- recovery codes and challenge tokens only as SHA-256 hashes.
DO $migration$
BEGIN
    IF to_regclass('public.users') IS NOT NULL THEN
        CREATE TABLE IF NOT EXISTS user_mfa (
            user_id BIGINT PRIMARY KEY REFERENCES users(id),
            secret_ciphertext VARCHAR(512) NOT NULL,
            confirmed_at TIMESTAMP WITH TIME ZONE,
            last_used_step BIGINT,
            created_at TIMESTAMP WITH TIME ZONE NOT NULL,
            updated_at TIMESTAMP WITH TIME ZONE NOT NULL
        );
        CREATE TABLE IF NOT EXISTS mfa_recovery_codes (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            user_id BIGINT NOT NULL REFERENCES users(id),
            code_hash VARCHAR(64) NOT NULL,
            created_at TIMESTAMP WITH TIME ZONE NOT NULL,
            used_at TIMESTAMP WITH TIME ZONE,
            CONSTRAINT mfa_recovery_codes_unique UNIQUE (user_id, code_hash)
        );
        CREATE INDEX IF NOT EXISTS mfa_recovery_codes_user_idx ON mfa_recovery_codes(user_id);
        CREATE TABLE IF NOT EXISTS mfa_challenges (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            token_hash VARCHAR(64) NOT NULL UNIQUE,
            user_id BIGINT NOT NULL REFERENCES users(id),
            purpose VARCHAR(20) NOT NULL,
            attempts INTEGER NOT NULL DEFAULT 0,
            created_at TIMESTAMP WITH TIME ZONE NOT NULL,
            expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
            used_at TIMESTAMP WITH TIME ZONE
        );
        CREATE INDEX IF NOT EXISTS mfa_challenges_user_idx ON mfa_challenges(user_id);
        CREATE TABLE IF NOT EXISTS security_audit_events (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            user_id BIGINT,
            actor_user_id BIGINT,
            action VARCHAR(50) NOT NULL,
            details VARCHAR(500),
            performed_at TIMESTAMP WITH TIME ZONE NOT NULL
        );
        CREATE INDEX IF NOT EXISTS security_audit_events_user_idx ON security_audit_events(user_id, performed_at);
    END IF;
    IF to_regclass('public.refresh_tokens') IS NOT NULL THEN
        ALTER TABLE refresh_tokens
            ADD COLUMN IF NOT EXISTS session_id VARCHAR(36),
            ADD COLUMN IF NOT EXISTS user_agent VARCHAR(255),
            ADD COLUMN IF NOT EXISTS last_used_at TIMESTAMP WITH TIME ZONE,
            ADD COLUMN IF NOT EXISTS revoked_at TIMESTAMP WITH TIME ZONE,
            ADD COLUMN IF NOT EXISTS revoked_reason VARCHAR(40);
        -- Tokens issued before session management each count as their own session.
        UPDATE refresh_tokens SET session_id = gen_random_uuid()::text WHERE session_id IS NULL;
        CREATE INDEX IF NOT EXISTS refresh_tokens_session_idx ON refresh_tokens(session_id);
        CREATE INDEX IF NOT EXISTS refresh_tokens_user_idx ON refresh_tokens(user_id, revoked);
    END IF;
END;
$migration$;

-- V1-V5 were guarded with to_regclass() and therefore did nothing on an empty database, leaving schema creation to
-- Hibernate (ddl-auto=update) without any of the intended indexes. This migration owns the schema: every table is
-- created IF NOT EXISTS with the same column definitions and constraint names Hibernate generates, and the indexes
-- are created unconditionally. On an existing database only the missing indexes are added; no data is touched.

CREATE TABLE IF NOT EXISTS roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(30) NOT NULL,
    CONSTRAINT ukofx66keruapi6vyqpv6f2or37 UNIQUE (name)
);

CREATE TABLE IF NOT EXISTS permissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category VARCHAR(60),
    code VARCHAR(60) NOT NULL,
    name VARCHAR(150) NOT NULL,
    CONSTRAINT uk7lcb6glmvwlro3p2w2cewxtvd UNIQUE (code)
);

CREATE TABLE IF NOT EXISTS role_permissions (
    role_id BIGINT NOT NULL,
    permission_id BIGINT NOT NULL,
    PRIMARY KEY (role_id, permission_id),
    CONSTRAINT fkn5fotdgk8d1xvo8nav9uv3muc FOREIGN KEY (role_id) REFERENCES roles(id),
    CONSTRAINT fkegdk29eiy7mdtefy5c7eirr6e FOREIGN KEY (permission_id) REFERENCES permissions(id)
);

CREATE TABLE IF NOT EXISTS organizations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    address VARCHAR(500),
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    description VARCHAR(500),
    description_translations JSONB,
    enabled BOOLEAN NOT NULL,
    last_verified_at TIMESTAMP(6) WITH TIME ZONE,
    latitude DOUBLE PRECISION,
    longitude DOUBLE PRECISION,
    map_url VARCHAR(500),
    name VARCHAR(150) NOT NULL,
    name_translations JSONB,
    official_source_url VARCHAR(500),
    phone VARCHAR(40),
    region_code VARCHAR(20),
    verification_outdated BOOLEAN NOT NULL,
    verified_by_user_id BIGINT,
    working_hours VARCHAR(500),
    CONSTRAINT ukp9pbw3flq9hkay8hdx3ypsldy UNIQUE (name)
);

CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    credentials_updated_at TIMESTAMP(6) WITH TIME ZONE,
    email VARCHAR(120) NOT NULL,
    enabled BOOLEAN NOT NULL,
    first_name VARCHAR(70) NOT NULL,
    last_name VARCHAR(70) NOT NULL,
    must_change_password BOOLEAN NOT NULL,
    password VARCHAR(255) NOT NULL,
    phone VARCHAR(20),
    role_id BIGINT NOT NULL,
    CONSTRAINT uk6dotkott2kjsp8vw4d0m25fb7 UNIQUE (email),
    CONSTRAINT fkp56c1712k691lhsyewcssf40f FOREIGN KEY (role_id) REFERENCES roles(id)
);

CREATE TABLE IF NOT EXISTS user_organizations (
    user_id BIGINT NOT NULL,
    organization_id BIGINT NOT NULL,
    PRIMARY KEY (user_id, organization_id),
    CONSTRAINT fkb1dy30eqc119tl9hqsictw52h FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT fkajx110b5wolrsi0jm57dlmn0t FOREIGN KEY (organization_id) REFERENCES organizations(id)
);

CREATE TABLE IF NOT EXISTS languages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    active BOOLEAN NOT NULL,
    code VARCHAR(64) NOT NULL,
    is_default BOOLEAN NOT NULL,
    name_native VARCHAR(100) NOT NULL,
    CONSTRAINT ukmyc139vxcejowe4q8qm3ca5jn UNIQUE (code)
);

CREATE TABLE IF NOT EXISTS refresh_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    last_used_at TIMESTAMP(6) WITH TIME ZONE,
    revoked BOOLEAN NOT NULL,
    revoked_at TIMESTAMP(6) WITH TIME ZONE,
    revoked_reason VARCHAR(40),
    session_id VARCHAR(36),
    token_hash VARCHAR(64) NOT NULL,
    user_agent VARCHAR(255),
    user_id BIGINT NOT NULL,
    CONSTRAINT uko2mlirhldriil2y7krapq4frt UNIQUE (token_hash),
    CONSTRAINT fk1lih5y2npsf8u5o3vhdb9y0os FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE TABLE IF NOT EXISTS password_reset_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel VARCHAR(20) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    initiated_by_user_id BIGINT,
    invalidated_at TIMESTAMP(6) WITH TIME ZONE,
    token_hash VARCHAR(64) NOT NULL,
    used_at TIMESTAMP(6) WITH TIME ZONE,
    user_id BIGINT NOT NULL,
    CONSTRAINT ukajre85ybxavf1tt4omkrs5p6g UNIQUE (token_hash),
    CONSTRAINT fkk3ndxg5xp6v7wd4gjyusp15gq FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT password_reset_tokens_channel_check CHECK (channel IN ('ADMIN', 'SELF_SERVICE'))
);

CREATE TABLE IF NOT EXISTS user_mfa (
    user_id BIGINT PRIMARY KEY REFERENCES users(id),
    confirmed_at TIMESTAMP(6) WITH TIME ZONE,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    last_used_step BIGINT,
    secret_ciphertext VARCHAR(512) NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE TABLE IF NOT EXISTS mfa_recovery_codes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code_hash VARCHAR(64) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    used_at TIMESTAMP(6) WITH TIME ZONE,
    user_id BIGINT NOT NULL,
    CONSTRAINT mfa_recovery_codes_unique UNIQUE (user_id, code_hash)
);

CREATE TABLE IF NOT EXISTS mfa_challenges (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attempts INTEGER NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    purpose VARCHAR(20) NOT NULL,
    token_hash VARCHAR(64) NOT NULL,
    used_at TIMESTAMP(6) WITH TIME ZONE,
    user_id BIGINT NOT NULL,
    CONSTRAINT ukobq7vtsc9mi9o01cdpeelytno UNIQUE (token_hash),
    CONSTRAINT mfa_challenges_purpose_check CHECK (purpose IN ('VERIFY', 'ENROLL'))
);

CREATE TABLE IF NOT EXISTS security_audit_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action VARCHAR(50) NOT NULL,
    actor_user_id BIGINT,
    details VARCHAR(500),
    performed_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    user_id BIGINT
);

-- Indexes behind the per-request session check, token look-ups and audit listings (created unconditionally).
CREATE INDEX IF NOT EXISTS refresh_tokens_session_idx ON refresh_tokens(session_id);
CREATE INDEX IF NOT EXISTS refresh_tokens_user_idx ON refresh_tokens(user_id, revoked);
CREATE INDEX IF NOT EXISTS refresh_tokens_expires_idx ON refresh_tokens(expires_at);
CREATE INDEX IF NOT EXISTS password_reset_tokens_user_idx ON password_reset_tokens(user_id);
CREATE INDEX IF NOT EXISTS mfa_recovery_codes_user_idx ON mfa_recovery_codes(user_id);
CREATE INDEX IF NOT EXISTS mfa_challenges_user_idx ON mfa_challenges(user_id);
CREATE INDEX IF NOT EXISTS mfa_challenges_expires_idx ON mfa_challenges(expires_at);
CREATE INDEX IF NOT EXISTS security_audit_events_user_idx ON security_audit_events(user_id, performed_at);
CREATE INDEX IF NOT EXISTS users_role_idx ON users(role_id);
CREATE INDEX IF NOT EXISTS user_organizations_organization_idx ON user_organizations(organization_id);

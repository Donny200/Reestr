-- Provenance of interface translations and the persistent queue that fills missing ones by machine translation.
-- Forward-only and data-preserving: no row is deleted or rewritten here. Existing rows keep source = NULL until the
-- catalog synchronizer classifies them (equal to the shipped catalog value -> SEED, anything else -> HUMAN), so values
-- that administrators edited before provenance existed are never replaced.

ALTER TABLE translations ADD COLUMN IF NOT EXISTS source VARCHAR(16);
ALTER TABLE translations ADD COLUMN IF NOT EXISTS source_hash VARCHAR(64);
ALTER TABLE translations ADD COLUMN IF NOT EXISTS updated_at TIMESTAMP WITH TIME ZONE;
ALTER TABLE translations DROP CONSTRAINT IF EXISTS ck_translations_source;
ALTER TABLE translations ADD CONSTRAINT ck_translations_source
    CHECK (source IS NULL OR source IN ('SEED', 'HUMAN', 'MACHINE'));

-- Keys owned by the shipped catalog (src/main/resources/i18n/interface/en.json). Keys created by administrators through
-- /api/translation-keys stay managed = FALSE and are never deactivated by the synchronizer.
ALTER TABLE translation_keys ADD COLUMN IF NOT EXISTS managed BOOLEAN NOT NULL DEFAULT FALSE;

CREATE TABLE IF NOT EXISTS interface_translation_jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    language_code VARCHAR(64) NOT NULL,
    status VARCHAR(16) NOT NULL,
    provider_code VARCHAR(32),
    attempts INTEGER NOT NULL DEFAULT 0,
    missing_keys INTEGER NOT NULL DEFAULT 0,
    translated_keys INTEGER NOT NULL DEFAULT 0,
    requested_at TIMESTAMP WITH TIME ZONE NOT NULL,
    next_attempt_at TIMESTAMP WITH TIME ZONE NOT NULL,
    started_at TIMESTAMP WITH TIME ZONE,
    finished_at TIMESTAMP WITH TIME ZONE,
    last_error VARCHAR(500),
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uk_interface_translation_jobs_language UNIQUE (language_code),
    CONSTRAINT ck_interface_translation_jobs_status
        CHECK (status IN ('PENDING', 'RUNNING', 'DONE', 'FAILED', 'UNSUPPORTED'))
);

CREATE INDEX IF NOT EXISTS idx_interface_translation_jobs_due
    ON interface_translation_jobs (status, next_attempt_at);

